/**
 * Etiketlere göre yorumları filtrele
 * @param {string[]} tags - Filtrelenecek etiketler
 * @param {number} limit - Maksimum yorum sayısı
 */
export const getReviewsByTags = (tags, limit = 8) => {
  const filtered = googleReviews.filter(review =>
    review.tags.some(tag => tags.includes(tag))
  )
  return filtered.slice(0, limit)
}
